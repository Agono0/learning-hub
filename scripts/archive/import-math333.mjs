/**
 * MATH 333 pilot import — definition-first card pipeline (Nielsen's method):
 * skills + prerequisite DAG + course/lessons from the real lecture PDFs + FSRS cards.
 * Idempotent: cleans prior partial imports, runs in one transaction.
 * Run: node scripts/import-math333.mjs
 */
import Database from 'better-sqlite3'
import { readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'

// self-contained repo-root DB resolution (same rule as packages/db)
let root = process.cwd()
for (let i = 0; i < 10; i++) {
  if (
    existsSync(join(root, 'package.json')) &&
    readFileSync(join(root, 'package.json'), 'utf8').includes('"workspaces"')
  )
    break
  root = dirname(root)
}
const DB_PATH = process.env.LEARNING_HUB_DB ?? join(root, 'data', 'learning-hub.db')

const db = new Database(DB_PATH)
db.pragma('foreign_keys = ON')

const now = new Date().toISOString()
const deckName = 'MATH 333 — Abstract Algebra'

