/**
 * Agent A — linter tests. Each implemented rule gets one triggering case and
 * one passing case, plus deck-level interference detection.
 */
import { describe, expect, it } from 'vitest'
import { diceSimilarity, lintCard, lintDeck, normalizeForCompare } from '../src/linter'
import type { LintCardInput } from '../src/linter'

function card(overrides: Partial<LintCardInput> = {}): LintCardInput {
  return {
    id: 1,
    deckId: 1,
    type: 'basic',
    content: { basic: { front: 'What is the capital of France?', back: 'Paris' } },
    source: 'lecture-3',
    tags: ['geography'],
    ...overrides,
  }
}

function ruleIds(results: { ruleId: string }[]): string[] {
  return results.map((r) => r.ruleId)
}

describe('per-rule triggering', () => {
  it('W1 minimum information: two questions in a front', () => {
    const bad = card({ content: { basic: { front: 'What is X? What is Y?', back: 'Z' } } })
    expect(ruleIds(lintCard(bad))).toContain('W1-minimum-information')
    const good = card()
    expect(ruleIds(lintCard(good))).not.toContain('W1-minimum-information')
  })

  it('W2 avoid sets: 3+ enumerated items in the answer', () => {
    const bad = card({
      content: {
        basic: { front: 'Name the ancestors of Indo-European', back: 'Sanskrit, Greek, Latin' },
      },
    })
    expect(ruleIds(lintCard(bad))).toContain('W2-avoid-sets')
    const good = card()
    expect(ruleIds(lintCard(good))).not.toContain('W2-avoid-sets')
  })

  it('W3 answer length: >8 words', () => {
    const bad = card({
      content: {
        basic: {
          front: 'Define coset',
          back: 'a coset is a subset formed by multiplying all elements of a subgroup by one element',
        },
      },
    })
    const results = lintCard(bad)
    expect(ruleIds(results)).toContain('W3-answer-length')
    const good = card()
    expect(ruleIds(lintCard(good))).not.toContain('W3-answer-length')
  })

  it('W6 interference: near-duplicate front vs a sibling', () => {
    const a = card({
      id: 1,
      content: { basic: { front: 'What is the capital of France?', back: 'Paris' } },
    })
    const b = card({
      id: 2,
      content: { basic: { front: 'What is the capital of France,', back: 'Paris!' } },
    })
    const results = lintCard(b, [a])
    expect(ruleIds(results)).toContain('W6-interference')
    const distinct = card({
      id: 2,
      content: { basic: { front: 'Who wrote Hamlet?', back: 'Shakespeare' } },
    })
    expect(ruleIds(lintCard(distinct, [a]))).not.toContain('W6-interference')
  })

  it('W9 source missing', () => {
    expect(ruleIds(lintCard(card({ source: null })))).toContain('W9-source-missing')
    expect(ruleIds(lintCard(card()))).not.toContain('W9-source-missing')
  })

  it('W10 imagery: concrete-noun answer', () => {
    const bad = card({ content: { basic: { front: 'What is a lighthouse?', back: 'tower' } } })
    expect(ruleIds(lintCard(bad))).toContain('W10-imagery')
    const good = card({
      content: { basic: { front: 'What is a lighthouse?', back: 'signaling tower' } },
    })
    expect(ruleIds(lintCard(good))).not.toContain('W10-imagery')
  })

  it('W11 cloze suggestion: sentence-length basic answer', () => {
    const bad = card({
      content: {
        basic: {
          front: 'What does the subgroup generated by S do?',
          back: 'it is the smallest subgroup containing S',
        },
      },
    })
    expect(ruleIds(lintCard(bad))).toContain('W11-cloze-suggestion')
    const good = card()
    expect(ruleIds(lintCard(good))).not.toContain('W11-cloze-suggestion')
  })

  it('W14 context cue: bare pronoun without domain', () => {
    const bad = card({ content: { basic: { front: 'When was it discovered?', back: '1897' } } })
    expect(ruleIds(lintCard(bad))).toContain('W14-context-cue')
    const good = card({
      content: { basic: { front: 'In physics: when was the electron discovered?', back: '1897' } },
    })
    expect(ruleIds(lintCard(good))).not.toContain('W14-context-cue')
  })

  it('W18 date stamp: relative time words', () => {
    const bad = card({ content: { basic: { front: 'Who is the current champion?', back: 'A' } } })
    expect(ruleIds(lintCard(bad))).toContain('W18-date-stamp')
    const good = card({
      content: { basic: { front: 'Who won the 2025 championship?', back: 'A' } },
    })
    expect(ruleIds(lintCard(good))).not.toContain('W18-date-stamp')
  })

  it('W19 priority stamp: untagged card', () => {
    expect(ruleIds(lintCard(card({ tags: [] })))).toContain('W19-priority-stamp')
    expect(ruleIds(lintCard(card()))).not.toContain('W19-priority-stamp')
  })

  it('a clean card produces no errors or warnings', () => {
    const results = lintCard(card())
    expect(results.filter((r) => r.severity === 'error' || r.severity === 'warn')).toEqual([])
  })
})

describe('lintDeck', () => {
  it('runs interference checks within the same deck only', () => {
    const cards = [
      card({
        id: 1,
        deckId: 1,
        content: { basic: { front: 'What is the capital of France?', back: 'Paris' } },
      }),
      card({
        id: 2,
        deckId: 1,
        content: { basic: { front: 'What is the capital of France?', back: 'Paris' } },
      }),
      card({
        id: 3,
        deckId: 2,
        content: { basic: { front: 'What is the capital of France?', back: 'Paris' } },
      }),
    ]
    const entries = lintDeck(cards)
    const byId = new Map(entries.map((e) => [e.cardId, e.results]))
    expect(ruleIds(byId.get(1) ?? [])).toContain('W6-interference')
    expect(ruleIds(byId.get(2) ?? [])).toContain('W6-interference')
    // card 3 is alone in deck 2 → no sibling interference
    expect(ruleIds(byId.get(3) ?? [])).not.toContain('W6-interference')
  })
})

describe('similarity helpers', () => {
  it('diceSimilarity and normalization behave', () => {
    expect(diceSimilarity('What is X?', 'what is x')).toBe(1)
    expect(diceSimilarity('cat', 'car')).toBeLessThan(1)
    expect(diceSimilarity('abc', 'zzz')).toBe(0)
    expect(normalizeForCompare('  Héllo, WORLD!! ')).toBe('h llo world')
  })
})
