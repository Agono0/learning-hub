describe('parseCloze', () => {
  it('extracts answers and keeps marker text', () => {
    const parsed = parseCloze('The capital of France is {{c1::Paris}}.')
    expect(parsed.text).toBe('The capital of France is {{c1::Paris}}.')
    expect(parsed.answers).toEqual(['Paris'])
    expect(parsed.mode).toBe('basic')
  })

  it('orders answers by first occurrence and dedupes repeated indexes', () => {
    const parsed = parseCloze('{{c2::B}} then {{c1::A}} and {{c2::B}} again')
    expect(parsed.answers).toEqual(['B', 'A'])
    expect(parsed.mode).toBe('enumeration') // 2 distinct indexes
  })

  it('extracts optional hints', () => {
    const parsed = parseCloze('Paris is {{c1::France::country}} capital')
    expect(parsed.answers).toEqual(['France'])
    expect(parsed.hint).toBe('country')
  })

  it('respects an explicit mode', () => {
    expect(parseCloze('{{c1::42}}', 'typein').mode).toBe('typein')
  })

  it('handles answers with special characters (existing DB data)', () => {
    const parsed = parseCloze(
      '{{c1::<S>}} is the subgroup generated by S — the {{c2::smallest}} one.',
    )
    expect(parsed.answers).toEqual(['<S>', 'smallest'])
  })

  it('returns empty answers for marker-less text (validation catches it)', () => {
    expect(parseCloze('no markers here').answers).toEqual([])
  })
})

describe('clozeSegments', () => {
  it('splits text and blanks in order', () => {
    const segments = clozeSegments('A {{c1::x}} B {{c2::y}} C')
    expect(segments).toEqual([
      { kind: 'text', text: 'A ' },
      { kind: 'blank', index: 1, answer: 'x' },
      { kind: 'text', text: ' B ' },
      { kind: 'blank', index: 2, answer: 'y' },
      { kind: 'text', text: ' C' },
    ])
  })
})

describe('buildCloze', () => {
  it('wraps answers with markers', () => {
    expect(
      buildCloze('Paris is the capital of France', [{ answer: 'Paris' }, { answer: 'France' }]),
    ).toBe('{{c1::Paris}} is the capital of {{c2::France}}')
  })

  it('throws when an answer is missing', () => {
    expect(() => buildCloze('abc', [{ answer: 'zzz' }])).toThrow(/not found/)
  })
})

describe('pickBasicFront (varied phrasings)', () => {
  it('rotates front and variants deterministically by reps', () => {
    const basic = { front: 'Q1', variants: ['Q2', 'Q3'] }
    expect(pickBasicFront(basic, 0)).toBe('Q1')
    expect(pickBasicFront(basic, 1)).toBe('Q2')
    expect(pickBasicFront(basic, 2)).toBe('Q3')
    expect(pickBasicFront(basic, 3)).toBe('Q1')
  })

  it('falls back to the front without variants and guards negative reps', () => {
    expect(pickBasicFront({ front: 'Q' }, 7)).toBe('Q')
    expect(pickBasicFront({ front: 'Q', variants: ['V'] }, -3)).toBe('Q')
  })
})

describe('validateCardContent', () => {
  it('accepts valid content per format', () => {
    expect(validateCardContent('basic', { front: 'Q', back: 'A' }).ok).toBe(true)
    // dual coding: optional image reference on basic cards
    expect(validateCardContent('basic', { front: 'Q', back: 'A', imageId: 7 }).ok).toBe(true)
    expect(validateCardContent('basic', { front: 'Q', back: 'A', imageId: 0 }).ok).toBe(false)
    expect(
      validateCardContent('cloze', { text: 'x {{c1::y}}', answers: ['y'], mode: 'basic' }).ok,
    ).toBe(true)
    expect(
      validateCardContent('mcq', { question: 'Q', options: ['a', 'b'], correctIndex: 1 }).ok,
    ).toBe(true)
    expect(validateCardContent('typein', { question: 'Q', acceptedAnswers: ['a'] }).ok).toBe(true)
    expect(
      validateCardContent('occlusion', {
        imageId: 3,
        rects: [{ id: 'r1', x: 0, y: 0, w: 0.5, h: 0.5 }],
      }).ok,
    ).toBe(true)
    expect(
      validateCardContent('proof_step', {
        theorem: 'T',
        proofSteps: ['s1'],
        stepIndex: 0,
        justification: 'hypothesis',
      }).ok,
    ).toBe(true)
    expect(
      validateCardContent('grammar', { sentence: 'I go', pattern: 'present', target: 'go' }).ok,
    ).toBe(true)
    expect(
      validateCardContent('matching', {
        pairs: [
          { left: 'a', right: 'b' },
          { left: 'c', right: 'd' },
        ],
      }).ok,
    ).toBe(true)
  })

  it('rejects broken content with issue strings', () => {
    const bad = validateCardContent('mcq', { question: 'Q', options: ['a'], correctIndex: 5 })
    expect(bad.ok).toBe(false)
    if (!bad.ok) {
      expect(bad.errors.length).toBeGreaterThan(0)
      expect(bad.errors.some((e) => e.includes('correctIndex') || e.includes('options'))).toBe(true)
    }
    expect(
      validateCardContent('cloze', { text: 'no markers', answers: ['x'], mode: 'basic' }).ok,
    ).toBe(false)
    expect(validateCardContent('basic', { front: 'Q' }).ok).toBe(false) // missing back
  })

  it('wrapped data is CardContent-shaped', () => {
    const ok = validateCardContent('typein', { question: 'Q', acceptedAnswers: ['a', 'aa'] })
    expect(ok.ok).toBe(true)
    if (ok.ok) expect(ok.data).toEqual({ typein: { question: 'Q', acceptedAnswers: ['a', 'aa'] } })
  })

  it('validateCardContent accepts both wrapped CardContent and raw format payloads (DEF-009)', () => {
    const raw = { front: 'Front', back: 'Back' }
    const wrapped = { basic: { front: 'Front', back: 'Back' } }
    expect(validateCardContent('basic', raw).ok).toBe(true)
    expect(validateCardContent('basic', wrapped).ok).toBe(true)

    const wrappedCloze = { cloze: { text: 'x {{c1::y}}', answers: ['y'], mode: 'basic' as const } }
    expect(validateCardContent('cloze', wrappedCloze).ok).toBe(true)
  })
})

describe('interleaveQueue', () => {
  const rng = () => 0.42 // deterministic

  it('never places two cards of the same deck adjacently when avoidable', () => {
    const cards = [
      ...Array.from({ length: 3 }, (_, i) => ({ id: i, deckId: 1 })),
      ...Array.from({ length: 3 }, (_, i) => ({ id: 10 + i, deckId: 2 })),
      ...Array.from({ length: 3 }, (_, i) => ({ id: 20 + i, deckId: 3 })),
    ]
    const out = interleaveQueue(cards, rng)
    expect(out).toHaveLength(9)
    for (let i = 1; i < out.length; i++) {
      expect(out[i].deckId).not.toBe(out[i - 1].deckId)
    }
  })

  it('keeps all cards and shuffles within decks', () => {
    const cards = Array.from({ length: 20 }, (_, i) => ({ id: i, deckId: i % 2 }))
    const out = interleaveQueue(cards, rng)
    expect([...out].sort((a, b) => a.id - b.id)).toEqual([...cards].sort((a, b) => a.id - b.id))
  })

  it('handles a single deck (no cross-deck fairness possible)', () => {
    const cards = Array.from({ length: 5 }, (_, i) => ({ id: i, deckId: 1 }))
    const out = interleaveQueue(cards, rng)
    expect(out).toHaveLength(5)
  })
})

describe('syncBulletCard', () => {
  it('detects cloze bullets', () => {
    const out = syncBulletCard('- The capital of {{c1::France}} is {{c2::Paris}}', 31)
    expect(out.type).toBe('cloze')
    expect(out.content.cloze?.answers).toEqual(['France', 'Paris'])
    expect(out.cardId).toBe(31)
  })

  it('detects Q:/A: bullets', () => {
    const out = syncBulletCard('Q: What is a group?\nA: A set with an associative operation', 32)
    expect(out.type).toBe('basic')
    expect(out.content.basic?.front).toContain('What is a group?')
    expect(out.content.basic?.back).toContain('associative')
  })

  it('detects single-line Q:/A: bullets (no newline between question and answer)', () => {
    const out = syncBulletCard('- Q: What is a group? A: A set with an associative operation', 36)
    expect(out.type).toBe('basic')
    expect(out.content.basic?.front).toBe('What is a group?')
    expect(out.content.basic?.back).toBe('A set with an associative operation')
    // Output must still pass validation (DEF-009)
    expect(validateCardContent(out.type, out.content).ok).toBe(true)
  })

  it('single-line Q:/A: does not truncate questions containing enumeration markers', () => {
    const out = syncBulletCard('Q: Options are a) yes b) no A: yes', 37)
    expect(out.content.basic?.front).toBe('Options are a) yes b) no')
    expect(out.content.basic?.back).toBe('yes')
  })

  it('single-line Q:/A: without an answer marker still falls back to front-only', () => {
    const out = syncBulletCard('Q: what is a group', 38)
    expect(out.type).toBe('basic')
    expect(out.content.basic?.front).toBe('Q: what is a group')
    expect(out.content.basic?.back).toBe('...')
  })

  it('detects :: and | separators', () => {
    expect(syncBulletCard('Lagrange :: |H| divides |G|', 33).content.basic?.back).toBe(
      '|H| divides |G|',
    )
    expect(syncBulletCard('coset | a subgroup orbit', 34).content.basic?.back).toBe(
      'a subgroup orbit',
    )
  })

  it('strips bullet markers and falls back to front-only basic with valid placeholder', () => {
    const out = syncBulletCard('* normal subgroup', 35)
    expect(out.type).toBe('basic')
    expect(out.content.basic?.front).toBe('normal subgroup')
    expect(out.content.basic?.back).toBe('...')
    // Crucial DEF-009 check: output must pass validateCardContent!
    const validated = validateCardContent(out.type, out.content)
    expect(validated.ok).toBe(true)
  })

  it('stripBulletMarker removes markdown enumeration', () => {
    expect(stripBulletMarker('1. first')).toBe('first')
    expect(stripBulletMarker('- dash')).toBe('dash')
    expect(stripBulletMarker('plain')).toBe('plain')
  })
})

describe('evaluateClozeAnswer & evaluateTypeinAnswer (DEF-002)', () => {
  it('evaluates single-blank cloze with exact, case-insensitive, and trimmed matches', () => {
    const cloze = { text: 'The capital of France is {{c1::Paris}}.' }
    expect(evaluateClozeAnswer(cloze, 'Paris').isCorrect).toBe(true)
    expect(evaluateClozeAnswer(cloze, 'paris').isCorrect).toBe(true)
    expect(evaluateClozeAnswer(cloze, '  Paris  ').isCorrect).toBe(true)
    expect(evaluateClozeAnswer(cloze, 'London').isCorrect).toBe(false)
    expect(evaluateClozeAnswer(cloze, '').isCorrect).toBe(false)
  })

  it('evaluates multi-blank cloze with Record input by index', () => {
    const cloze = { text: '{{c1::Mitochondria}} is the {{c2::powerhouse}} of the cell.' }
    expect(evaluateClozeAnswer(cloze, { 1: 'mitochondria', 2: 'powerhouse' }).isCorrect).toBe(true)
    expect(evaluateClozeAnswer(cloze, { 1: 'mitochondria', 2: 'nucleus' }).isCorrect).toBe(false)
    const partial = evaluateClozeAnswer(cloze, { 1: 'mitochondria', 2: 'nucleus' })
    expect(partial.blanks[0].isCorrect).toBe(true)
    expect(partial.blanks[1].isCorrect).toBe(false)
  })

  it('evaluates multi-blank cloze with array input', () => {
    const cloze = { text: '{{c1::Alpha}} and {{c2::Beta}}' }
    expect(evaluateClozeAnswer(cloze, ['Alpha', 'Beta']).isCorrect).toBe(true)
    expect(evaluateClozeAnswer(cloze, ['Alpha', 'Gamma']).isCorrect).toBe(false)
  })

  it('deduplicates identical blank indices', () => {
    const cloze = { text: '{{c1::Same}} here and {{c1::Same}} there' }
    expect(evaluateClozeAnswer(cloze, { 1: 'same' }).isCorrect).toBe(true)
    expect(evaluateClozeAnswer(cloze, { 1: 'same' }).blanks).toHaveLength(1)
  })

  it('evaluates typein answers against acceptedAnswers', () => {
    const typein = { acceptedAnswers: ['O(N log N)', 'N log N', 'O(n log n)'] }
    expect(evaluateTypeinAnswer(typein, 'O(n log n)')).toBe(true)
    expect(evaluateTypeinAnswer(typein, '  n log n  ')).toBe(true)
    expect(evaluateTypeinAnswer(typein, 'O(N^2)')).toBe(false)
  })

  it('evaluates unified isCardAnswerCorrect', () => {
    const clozeCard = {
      cloze: { text: 'Test {{c1::Answer}}', answers: ['Answer'], mode: 'typein' as const },
    }
    const typeinCard = { typein: { question: 'Q', acceptedAnswers: ['Ans'] } }
    expect(isCardAnswerCorrect(clozeCard, 'answer')).toBe(true)
    expect(isCardAnswerCorrect(typeinCard, 'ans')).toBe(true)
    expect(isCardAnswerCorrect(typeinCard, 'wrong')).toBe(false)
    expect(isCardAnswerCorrect({}, 'anything')).toBe(false)
  })
})

describe('property: cloze parse → segments agree on answers', () => {
  it('every parsed answer appears as a segment answer', () => {
    const answerArb = fc.string({ minLength: 1, maxLength: 8 }).filter((s) => !/[{}:]/.test(s))
    const textArb = fc
      .tuple(
        answerArb,
        answerArb,
        fc.string({ maxLength: 10 }).filter((s) => !/[{}:]/.test(s)),
      )
      .map(([a1, a2, filler]) => `${filler} {{c1::${a1}}} mid {{c2::${a2}}} end`)
    fc.assert(
      fc.property(textArb, (text) => {
        const parsed = parseCloze(text)
        expect(parsed.answers).toHaveLength(2)
        const blanks = clozeSegments(text).filter((s) => s.kind === 'blank')
        expect(blanks.map((b) => (b.kind === 'blank' ? b.answer : ''))).toEqual(parsed.answers)
        expect(parsed.text).toBe(text)
      }),
    )
  })
})
