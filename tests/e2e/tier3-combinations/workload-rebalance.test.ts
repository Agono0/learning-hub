import { describe, it, expect, beforeAll } from 'vitest'
import { callRoute } from '../helpers/api-client'
import { db, decks, cards, revlog } from '@learning-hub/db'
import { eq } from 'drizzle-orm'
import * as workloadRoute from '../../../apps/web/app/api/workload/route'

describe('Tier 3 E2E: Workload Rebalancing, Backlog Catch-Up & Rule 7 Invariant', () => {
  let deckId: number
  const initialStability = 12.5
  const initialDifficulty = 4.2

  beforeAll(async () => {
    const [deck] = await db.insert(decks).values({ name: 'Workload Backlog Deck' }).returning()
    deckId = deck!.id

    const now = Date.now()
    // Seed 12 overdue review cards
    for (let i = 0; i < 12; i++) {
      await db.insert(cards).values({
        deckId,
        type: 'basic',
        content: { basic: { front: `Overdue Concept ${i}`, back: `Answer ${i}` } },
        due: new Date(now - (i + 1) * 86_400_000).toISOString(), // 1 to 12 days in the past
        stability: initialStability,
        difficulty: initialDifficulty,
        state: 2, // Review state
        reps: 3,
        lapses: 0,
        scheduledDays: 12,
      })
    }
  })

  it('detects overdue review backlog and shifts due dates while preserving Rule 7', async () => {
    // 1. Forecast and inspect overdue backlog
    const getRes = await callRoute<{
      ok: boolean
      totalCards: number
      overdueCount: number
      forecast: Array<{ date: string; dueCount: number }>
    }>(workloadRoute.GET, {
      method: 'GET',
      query: { deckId, days: 14 },
    })

    expect(getRes.status).toBe(200)
    expect(getRes.data.ok).toBe(true)
    expect(getRes.data.totalCards).toBe(12)
    expect(getRes.data.overdueCount).toBe(12)

    // Count revlog entries before catch up
    const revlogBefore = await db.select().from(revlog)
    const revlogCountBefore = revlogBefore.length

    // 2. Execute backlog recovery with dailyCap=5
    const catchUpRes = await callRoute<{
      ok: boolean
      action: string
      shiftedCount: number
      shifts: Array<{ cardId: number; oldDue: string; newDue: string }>
      forecast: Array<{ date: string; dueCount: number }>
    }>(workloadRoute.POST, {
      method: 'POST',
      body: {
        action: 'catch_up',
        deckId,
        dailyCap: 5,
      },
    })

    expect(catchUpRes.status).toBe(200)
    expect(catchUpRes.data.ok).toBe(true)
    expect(catchUpRes.data.action).toBe('catch_up')
    expect(catchUpRes.data.shiftedCount).toBe(12)
    expect(catchUpRes.data.shifts.length).toBe(12)

    // 3. Inspect cards post-shift
    const deckCards = await db.select().from(cards).where(eq(cards.deckId, deckId))

    for (const card of deckCards) {
      // Due date was shifted into the future or spread across days
      expect(card.due).toBeDefined()

      // STRICT RULE 7 INVARIANT: Memory parameters must NEVER be altered by workload balancing
      expect(card.stability).toBe(initialStability)
      expect(card.difficulty).toBe(initialDifficulty)
      expect(card.state).toBe(2) // Still review state
      expect(card.reps).toBe(3)
      expect(card.lapses).toBe(0)
    }

    // STRICT RULE 8 & RULE 7 INVARIANT: Revlog must NOT have any new rows generated by balancing
    const revlogAfter = await db.select().from(revlog)
    expect(revlogAfter.length).toBe(revlogCountBefore)
  })
})
