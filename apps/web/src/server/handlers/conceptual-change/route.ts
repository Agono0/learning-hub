/**
 * Runtime-neutral API handler for the Conceptual Change & Ontological Category
 * Shift Studio.
 *
 * Grounded in:
 * - Michelene T. H. Chi (1992, 2008, 2013): Ontological Category Shift
 *   Framework — misconceptions as ontological misattributions, diagnosed via
 *   the six process-attribute dimensions and the direct/emergent discrepancy.
 * - Stella Vosniadou (1994, 2002): Framework Theory & Synthetic Mental Models
 *   (the compromise-risk radar).
 * - Andrea diSessa (1988, 1993): Knowledge in Pieces — phenomenological
 *   primitives (p-prims) and their scientific recontextualization.
 * - Posner, Strike, Hewson & Gertzog (1982): the four accommodation
 *   conditions (Dissatisfaction, Intelligibility, Plausibility, Fruitfulness).
 *
 * Actions (zod-discriminated):
 * - `diagnose`: the full ontological diagnosis for a learner state — Chi
 *   discrepancy gap, Posner accommodation index, Vosniadou synthetic-compromise
 *   risk, conceptual-shift readiness and the mental-model stage classifier.
 * - `cards`: FSRS-6 conceptual-shift flashcards generated by the core engine.
 *
 * GET returns the calibrated misconception scenarios plus the Chi attribute
 * catalog and the diSessa p-prim catalog so any host — web UI, headless
 * server, MCP, CLI — can render or drive the studio without importing the core
 * package. Pure content, no database reads: the endpoint is always available
 * (manual-mode guarantee, rule 9).
 */

import { z } from 'zod'
import {
  CALIBRATED_MISCONCEPTION_SCENARIOS,
  CANONICAL_ATTRIBUTE_CATALOG,
  CANONICAL_PPRIM_CATALOG,
  calculateConceptualChangeReadiness,
  calculateOntologicalDiscrepancyGap,
  detectSyntheticCompromiseRisk,
  generateFSRSConceptualShiftCards,
  OntologicalBranchSchema,
  OntologicalDiagnosisResultSchema,
  PosnerConditionsSchema,
  ProcessAttributeCategorySchema,
  ProcessAttributeSchema,
  type ConceptualMisconceptionScenario,
  type MentalModelStage,
  type OntologicalDiagnosisResult,
} from '@learning-hub/core/conceptual-change'
import { readJson, withRoute } from '@/lib/api'

const postConceptualChangeBodySchema = z.discriminatedUnion('action', [
  z.object({
    action: z.literal('diagnose'),
    scenarioId: z.string().min(1),
    /** The learner's Chi-6 attribute choices, keyed by dimension (complete record). */
    selectedAttributes: z.record(ProcessAttributeCategorySchema, ProcessAttributeSchema),
    /** The ontological branch the learner currently assigns the phenomenon to. */
    learnerBranch: OntologicalBranchSchema,
    /** Posner et al. (1982) accommodation conditions, each clamped to 0..1. */
    posnerConditions: PosnerConditionsSchema,
  }),
  z.object({
    action: z.literal('cards'),
    scenarioId: z.string().min(1),
    /** The current diagnosis (kept in the contract for parity with the studio's
     * call shape; the generator currently reads only the scenario). */
    diagnosis: OntologicalDiagnosisResultSchema.optional(),
  }),
])

/**
 * Resolve a scenario id. Falls back to the first calibrated scenario — the
 * studio's own display default — so a stale id degrades to valid content
 * instead of a 404.
 */
function requireScenario(scenarioId: string): ConceptualMisconceptionScenario {
  return (
    CALIBRATED_MISCONCEPTION_SCENARIOS.find((s) => s.id === scenarioId) ??
    CALIBRATED_MISCONCEPTION_SCENARIOS[0]
  )
}

/**
 * Neutral diagnosis used when a `cards` caller omits one. The card generator
 * currently reads only the scenario (its diagnosis parameter is reserved for
 * future conditioning), so any in-schema value suffices; `discrepancyGap: 0.5`
 * is the engine's own neutral gap for an empty attribute selection.
 */
function neutralDiagnosis(scenario: ConceptualMisconceptionScenario): OntologicalDiagnosisResult {
  return {
    scenarioId: scenario.id,
    learnerBranch: scenario.naiveOntologicalBranch,
    targetBranch: scenario.targetOntologicalBranch,
    isOntologicalMismatch: scenario.naiveOntologicalBranch !== scenario.targetOntologicalBranch,
    discrepancyGap: 0.5,
    detectedPPrim: scenario.dominantPPrim,
    mentalModelStage: 'initial_naive_model',
    posnerAccommodationIndex: 0,
    syntheticCompromiseRisk: 0,
    conceptualShiftReadiness: 0,
  }
}

/**
 * GET /api/conceptual-change — the calibrated misconception scenario corpus,
 * the Chi (2013) process-attribute catalog and the diSessa (1993) p-prim
 * catalog (static content).
 */
export const GET = withRoute(async () => {
  return Response.json({
    ok: true,
    scenarios: CALIBRATED_MISCONCEPTION_SCENARIOS,
    attributeCatalog: CANONICAL_ATTRIBUTE_CATALOG,
    pprimCatalog: CANONICAL_PPRIM_CATALOG,
  })
})

/**
 * POST /api/conceptual-change — engine-backed studio operations:
 * `diagnose` (full ontological diagnosis for a learner state) and `cards`
 * (FSRS-6 conceptual-shift flashcards for a scenario).
 */
export const POST = withRoute(async (req) => {
  const body = await readJson(req, postConceptualChangeBodySchema)

  if (body.action === 'diagnose') {
    const scenario = requireScenario(body.scenarioId)

    const discrepancyGap = calculateOntologicalDiscrepancyGap({
      selectedAttributes: Object.values(body.selectedAttributes),
      scenario,
    })
    // The Posner accommodation index is the studio's own inline weighted sum
    // (deliberately unrounded) rather than the engine's
    // `evaluatePosnerAccommodationIndex`, which rounds to 3 decimals — the
    // exact expression keeps API results bit-identical with the studio's
    // offline fallback, so the UI never flips a displayed value when the API
    // response replaces the local computation.
    const posnerAccommodationIndex =
      0.35 * body.posnerConditions.dissatisfaction +
      0.25 * body.posnerConditions.intelligibility +
      0.25 * body.posnerConditions.plausibility +
      0.15 * body.posnerConditions.fruitfulness
    const syntheticCompromiseRisk = detectSyntheticCompromiseRisk({
      discrepancyGap,
      posnerConditions: body.posnerConditions,
    })
    const conceptualShiftReadiness = calculateConceptualChangeReadiness({
      posnerIndex: posnerAccommodationIndex,
      discrepancyGap,
      syntheticRisk: syntheticCompromiseRisk,
    })

    // Mental-model stage classifier (Vosniadou): full emergent shift requires
    // both high readiness AND the learner's own emergent assignment; a strong
    // synthetic compromise otherwise pins the hybrid stage.
    let mentalModelStage: MentalModelStage = 'initial_naive_model'
    if (conceptualShiftReadiness >= 0.75 && body.learnerBranch === 'emergent_process') {
      mentalModelStage = 'scientific_emergent_model'
    } else if (syntheticCompromiseRisk > 0.5) {
      mentalModelStage = 'synthetic_compromise_model'
    }

    const diagnosis: OntologicalDiagnosisResult = {
      scenarioId: scenario.id,
      learnerBranch: body.learnerBranch,
      targetBranch: scenario.targetOntologicalBranch,
      isOntologicalMismatch: body.learnerBranch !== scenario.targetOntologicalBranch,
      discrepancyGap,
      detectedPPrim: scenario.dominantPPrim,
      mentalModelStage,
      posnerAccommodationIndex,
      syntheticCompromiseRisk,
      conceptualShiftReadiness,
    }
    return Response.json({ ok: true, diagnosis })
  }

  // action === 'cards'
  const scenario = requireScenario(body.scenarioId)
  const cards = generateFSRSConceptualShiftCards(
    scenario,
    body.diagnosis ?? neutralDiagnosis(scenario),
  )
  return Response.json({ ok: true, cards })
})
