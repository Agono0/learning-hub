/** Largest accepted publish body (a share string plus metadata). Assumed limit. */
const PUBLISH_MAX_BYTES = 512 * 1024

function safeTags(raw: unknown): string[] {
  try {
    const v = typeof raw === 'string' ? JSON.parse(raw) : raw
    return Array.isArray(v) ? v.filter((t): t is string => typeof t === 'string') : []
  } catch {
    return []
  }
}

export interface Env {
  DB?: D1Database
  STUDY_ROOM?: DurableObjectNamespace
  BOSS_RAID?: DurableObjectNamespace
  LEAGUE_ROOM?: DurableObjectNamespace
  /** Authenticated leagues route only when this is exactly "true". Ships unset. */
  LEAGUES_ENABLED?: string
  GITHUB_ISSUE_TOKEN?: string
  GITHUB_REPO?: string
  /** Trusted public host of this worker; signed requests are refused when it is unset. */
  EXPECTED_HOST?: string
}

function corsHeaders(): HeadersInit {
  return {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, PUT, DELETE, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization, X-Requested-With',
  }
}

/**
 * A library item is attributed to a verified device only when its id came from the signed
 * request digest (`item_` + 32 hex). Anonymous ids are `item_<millis>_<rand>`, and items
 * from before signing are the same shape, so they are never reported as verified. This is
 * derived from data only the worker writes, so it needs no schema change.
 *
 * INVARIANT for any future write path to community_library: ids must be generated by the
 * worker, never taken from a caller, and only the signed publish path may produce the
 * `item_` + 32 hex form. A path that restores, imports or lets callers choose ids must first
 * move to an explicit author_verified column (D1 migration), or this check is no longer sound.
 */
export function isVerifiedItemId(id: unknown): boolean {
  return typeof id === 'string' && /^item_[0-9a-f]{32}$/.test(id)
}

/** A community_library row as stored in D1 (tags is a JSON array string). */
interface LibraryRow {
  id: string
  type: string
  title: string
  description: string | null
  author: string
  downloads: number
  rating: number
  tags: string | null
  share_string: string
  published_at: string
}

/** Tags column → string[]; a corrupt value yields [] instead of failing the search. */
function parseTags(raw: string | null): string[] {
  try {
    const v: unknown = JSON.parse(raw || '[]')
    return Array.isArray(v) ? v.filter((t): t is string => typeof t === 'string') : []
  } catch {
    return []
  }
}

function jsonResponse(data: unknown, status = 200): Response {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      'Content-Type': 'application/json',
      ...corsHeaders(),
    },
  })
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: corsHeaders() })
    }

    const url = new URL(request.url)
    const path = url.pathname

    try {
      // ── Health ──────────────────────────────────────────────────────────
      if (path === '/health' || path === '/') {
        return jsonResponse({
          ok: true,
          worker: 'learning-hub-engagement',
          version: '1.0.0',
        })
      }

      // ── Auth: Register Device Key ────────────────────────────────────────
      if (path === '/api/v1/auth/register-key' && request.method === 'POST') {
        const body = (await request.json()) as {
          pubkey: string
          alias: string
          challenge?: string
          signature?: string
        }
        if (!body.pubkey || !body.alias) {
          return jsonResponse({ error: 'pubkey and alias are required' }, 400)
        }

        // Signature verification (ECDSA P-256 / SHA-256 over the challenge).
        // A signed challenge binds the alias to a key only its owner controls.
        if (!body.challenge || !body.signature) {
          return jsonResponse({ error: 'challenge and signature are required' }, 400)
        }
        if (!body.challenge.startsWith('lh-identity:v1:')) {
          return jsonResponse({ error: 'invalid challenge format' }, 400)
        }
        try {
          const pubRaw = Uint8Array.from(atob(body.pubkey), (c) => c.charCodeAt(0))
          const sigRaw = Uint8Array.from(atob(body.signature), (c) => c.charCodeAt(0))
          const cryptoKey = await crypto.subtle.importKey(
            'spki',
            pubRaw.buffer,
            { name: 'ECDSA', namedCurve: 'P-256' },
            false,
            ['verify'],
          )
          // The signed payload binds challenge + alias: a signature is only
          // valid for exactly this alias (no replay under another name).
          const signingPayload = `${body.challenge}|${body.alias}`
          const ok = await crypto.subtle.verify(
            { name: 'ECDSA', hash: 'SHA-256' },
            cryptoKey,
            sigRaw.buffer,
            new TextEncoder().encode(signingPayload),
          )
          if (!ok) return jsonResponse({ error: 'signature verification failed' }, 401)
        } catch {
          return jsonResponse({ error: 'malformed key or signature' }, 400)
        }

        // A key that is already registered keeps its stored id (no rebinding of existing rows);
        // a new key gets an id derived from the whole key, so keys no longer collide.
        let userId = await deriveUserId(body.pubkey)
        const nowIso = new Date().toISOString()
        const { clean: cleanAlias } = filterContentSafety(body.alias.slice(0, 40))

        if (env.DB) {
          const existing = await env.DB.prepare('SELECT id FROM users WHERE pubkey = ?')
            .bind(body.pubkey)
            .first<{ id: string }>()
          if (existing?.id) userId = existing.id
          await env.DB.prepare(
            `INSERT INTO users (id, pubkey, alias, created_at)
             VALUES (?, ?, ?, ?)
             ON CONFLICT(pubkey) DO UPDATE SET alias = excluded.alias`,
          )
            .bind(userId, body.pubkey, cleanAlias, nowIso)
            .run()
          // Existing accounts keep the id they were first registered under
          // (public_stats and other rows reference it). The upsert never
          // rewrites id, so report the stored one instead of the new
          // fingerprint: no silent reassignment of existing account data.
          const stored = await env.DB.prepare('SELECT id FROM users WHERE pubkey = ?')
            .bind(body.pubkey)
            .first<{ id: string }>()
          if (stored?.id) userId = stored.id
        }

        return jsonResponse({ ok: true, userId, alias: cleanAlias })
      }

      // ── Authenticated Leagues (inactive groundwork, off unless enabled) ───
      const leagueRoute = path.match(
        /^\/api\/v1\/leagues\/(create|([a-z0-9][a-z0-9-]{5,39})\/(mutate|state))$/,
      )
      if (leagueRoute) {
        if (env.LEAGUES_ENABLED !== 'true' || !env.LEAGUE_ROOM) {
          return jsonResponse(
            { error: 'Authenticated leagues are not enabled', enabled: false },
            503,
          )
        }
        if (leagueRoute[1] === 'create') {
          if (request.method !== 'POST') return jsonResponse({ error: 'method not allowed' }, 405)
          const body = ((await request.json().catch(() => null)) ?? {}) as {
            id?: unknown
            title?: unknown
            seasonStart?: unknown
          }
          if (
            typeof body.id !== 'string' ||
            !/^[a-z0-9][a-z0-9-]{5,39}$/.test(body.id) ||
            typeof body.title !== 'string' ||
            typeof body.seasonStart !== 'string' ||
            !/^\d{4}-\d{2}-\d{2}$/.test(body.seasonStart)
          ) {
            return jsonResponse(
              { error: 'id, title and seasonStart (YYYY-MM-DD) are required' },
              400,
            )
          }
          const { clean: title } = filterContentSafety(body.title.slice(0, 80))
          const league = createLeague({ id: body.id, title, seasonStart: body.seasonStart })
          const stub = env.LEAGUE_ROOM.get(env.LEAGUE_ROOM.idFromName(body.id))
          return stub.fetch('http://do/init', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ league }),
          })
        }
        const leagueId = leagueRoute[2]!
        const action = leagueRoute[3]!
        const stub = env.LEAGUE_ROOM.get(env.LEAGUE_ROOM.idFromName(leagueId))
        if (action === 'state') {
          if (request.method !== 'GET') return jsonResponse({ error: 'method not allowed' }, 405)
          return stub.fetch('http://do/state')
        }
        if (request.method !== 'POST') return jsonResponse({ error: 'method not allowed' }, 405)
        return stub.fetch('http://do/mutate', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: await request.text(),
        })
      }

      // ── Live Study Rooms ─────────────────────────────────────────────────
      if (path === '/api/v1/rooms/create' && request.method === 'POST') {
        const body = ((await request.json().catch(() => ({}))) ?? {}) as {
          title?: string
          topic?: string
          pomodoroWorkMinutes?: number
          pomodoroBreakMinutes?: number
        }

        if (!env.STUDY_ROOM) {
          return jsonResponse({ error: 'Study rooms are not enabled on this worker' }, 503)
        }
        const code = makeRoomCode()
        const id = env.STUDY_ROOM.idFromName(code)
        const roomObj = env.STUDY_ROOM.get(id)

        const title = body.title?.trim() || 'Focus Session'
        const { clean: cleanTitle } = filterContentSafety(title)

        const initRes = await roomObj.fetch('http://do/init', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            code,
            title: cleanTitle,
            topic: body.topic,
            pomodoroWorkMinutes: body.pomodoroWorkMinutes ?? 25,
            pomodoroBreakMinutes: body.pomodoroBreakMinutes ?? 5,
          }),
        })
        const data = await initRes.json()
        return jsonResponse({ ok: true, code, ...data })
      }

      // WebSocket Upgrade: /api/v1/rooms/:code/ws
      const roomWsMatch = path.match(/^\/api\/v1\/rooms\/([A-Z0-9]{6})\/ws$/)
      if (roomWsMatch) {
        if (!env.STUDY_ROOM) {
          return jsonResponse({ error: 'Study rooms are not enabled on this worker' }, 503)
        }
        const code = roomWsMatch[1]!
        const id = env.STUDY_ROOM.idFromName(code)
        const roomObj = env.STUDY_ROOM.get(id)
        return roomObj.fetch(request)
      }

      // Room Info: /api/v1/rooms/:code/info
      const roomInfoMatch = path.match(/^\/api\/v1\/rooms\/([A-Z0-9]{6})\/info$/)
      if (roomInfoMatch) {
        if (!env.STUDY_ROOM) {
          return jsonResponse({ error: 'Study rooms are not enabled on this worker' }, 503)
        }
        const code = roomInfoMatch[1]!
        const id = env.STUDY_ROOM.idFromName(code)
        const roomObj = env.STUDY_ROOM.get(id)
        const res = await roomObj.fetch('http://do/info')
        const data = await res.json()
        return jsonResponse(data)
      }

      // ── Party Boss Raids ─────────────────────────────────────────────────
      if (path === '/api/v1/raids/create' && request.method === 'POST') {
        if (!env.BOSS_RAID) {
          return jsonResponse({ error: 'Boss raids are not enabled on this worker' }, 503)
        }
        const body = ((await request.json().catch(() => ({}))) ?? {}) as {
          bossKey?: unknown
        }
        const bossKey = body.bossKey === undefined ? 'chronos' : body.bossKey
        if (!isOwnBossKey(BOSS_ROSTER, bossKey)) {
          return jsonResponse({ error: 'Unknown bossKey' }, 400)
        }
        const boss = BOSS_ROSTER[bossKey]!
        const raidId = `raid_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`

        const id = env.BOSS_RAID.idFromName(raidId)
        const raidObj = env.BOSS_RAID.get(id)

        const initRes = await raidObj.fetch('http://do/init', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            id: raidId,
            bossKey: boss.key,
            bossName: boss.name,
            bossHp: boss.maxHp * 2, // scaled for party raid
            bossMaxHp: boss.maxHp * 2,
            partyHp: 500,
            partyMaxHp: 500,
            status: 'waiting',
          }),
        })
        const data = await initRes.json()
        return jsonResponse({ ok: true, raidId, ...data })
      }

      // WebSocket Upgrade: /api/v1/raids/:id/ws
      const raidWsMatch = path.match(/^\/api\/v1\/raids\/([a-zA-Z0-9_-]+)\/ws$/)
      if (raidWsMatch) {
        if (!env.BOSS_RAID) {
          return jsonResponse({ error: 'Boss raids are not enabled on this worker' }, 503)
        }
        const raidId = raidWsMatch[1]!
        const id = env.BOSS_RAID.idFromName(raidId)
        const raidObj = env.BOSS_RAID.get(id)
        return raidObj.fetch(request)
      }

      // ── Community Library ────────────────────────────────────────────────
      if (path === '/api/v1/library/search' && request.method === 'GET') {
        const q = url.searchParams.get('q')?.toLowerCase() ?? ''
        const type = url.searchParams.get('type')

        if (!env.DB) {
          return jsonResponse({ ok: true, items: [] })
        }

        let query = 'SELECT * FROM community_library WHERE 1=1'
        const params: D1Value[] = []

        if (type) {
          query += ' AND type = ?'
          params.push(type)
        }
        if (q) {
          // Escape LIKE wildcards so a search for "100%" or "a_b" is literal.
          const needle = `%${q.replace(/[\\%_]/g, (m) => `\\${m}`)}%`
          query += " AND (LOWER(title) LIKE ? ESCAPE '\\' OR LOWER(description) LIKE ? ESCAPE '\\')"
          params.push(needle, needle)
        }
        query += ' ORDER BY downloads DESC LIMIT 50'

        const results = await env.DB.prepare(query)
          .bind(...params)
          .all<LibraryRow>()
        const items = results.results.map((r) => ({
          id: r.id,
          type: r.type,
          title: r.title,
          description: r.description,
          author: r.author,
          authorVerified: isVerifiedItemId(r.id),
          downloads: r.downloads,
          rating: r.rating,
          tags: parseTags(r.tags),
          shareString: r.share_string,
          publishedAt: r.published_at,
        }))

        return jsonResponse({ ok: true, items })
      }

      if (path === '/api/v1/library/publish' && request.method === 'POST') {
        const bytes = await readBytesCapped(request, PUBLISH_MAX_BYTES)
        if (bytes === null) return jsonResponse({ error: 'Payload too large' }, 413)
        const auth = await authenticateRequest(request, bytes, env)
        if (!auth.ok) return jsonResponse({ error: auth.error }, auth.status)

        let raw: unknown
        try {
          raw = JSON.parse(new TextDecoder().decode(bytes))
        } catch {
          return jsonResponse({ error: 'Invalid JSON body' }, 400)
        }
        // Only these fields come from the caller. Id, author, downloads, rating and publish
        // time are decided here (a caller used to be able to set all of them).
        const input = (raw && typeof raw === 'object' ? raw : {}) as Record<string, unknown>
        const principal = auth.principal
        const publishedMs =
          principal.kind === 'registered' ? Number(request.headers.get('x-lh-ts')) : Date.now()
        const candidate = communityItemSchema.safeParse({
          id:
            principal.kind === 'registered'
              ? `item_${principal.requestId.slice(0, 32)}`
              : `item_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
          type: input.type,
          title: input.title,
          description: input.description,
          tags: input.tags,
          shareString: input.shareString,
          author: principal.kind === 'registered' ? principal.alias : 'Anonymous',
          downloads: 0,
          rating: 5.0,
          publishedAt: new Date(publishedMs).toISOString(),
        })
        if (!candidate.success) return jsonResponse({ error: 'Invalid item' }, 400)
        const parsed = candidate.data

        const { clean: cleanTitle } = filterContentSafety(parsed.title)
        const { clean: cleanDesc } = filterContentSafety(parsed.description ?? '')
        const item = { ...parsed, title: cleanTitle, description: cleanDesc }

        if (env.DB) {
          // Atomic and idempotent: replaying the same signed request hits the same id and
          // changes nothing (an existing item and its counters are never overwritten).
          await env.DB.prepare(
            `INSERT INTO community_library (id, type, title, description, author, downloads, rating, tags, share_string, published_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
             ON CONFLICT(id) DO NOTHING`,
          )
            .bind(
              item.id,
              item.type,
              item.title,
              item.description,
              item.author,
              0,
              5.0,
              JSON.stringify(item.tags),
              item.shareString,
              item.publishedAt,
            )
            .run()
          if (principal.kind === 'registered') {
            const existing = await env.DB.prepare(
              'SELECT id, type, title, description, author, downloads, rating, tags, share_string, published_at FROM community_library WHERE id = ?',
            )
              .bind(item.id)
              .first<Record<string, unknown>>()
            if (existing) {
              return jsonResponse({
                ok: true,
                item: {
                  id: existing.id,
                  type: existing.type,
                  title: existing.title,
                  description: existing.description,
                  author: existing.author,
                  authorVerified: isVerifiedItemId(existing.id),
                  downloads: existing.downloads,
                  rating: existing.rating,
                  tags: safeTags(existing.tags),
                  shareString: existing.share_string,
                  publishedAt: existing.published_at,
                },
              })
            }
          }
        }

        return jsonResponse({
          ok: true,
          item: {
            ...item,
            authorVerified: principal.kind === 'registered' && isVerifiedItemId(item.id),
          },
        })
      }

      if (path === '/api/v1/library/download' && request.method === 'POST') {
        const raw: unknown = await request.json().catch(() => null)
        const id = (raw as { id?: unknown } | null)?.id
        if (typeof id !== 'string' || id.length === 0 || id.length > 100) {
          return jsonResponse({ error: 'id required' }, 400)
        }
        const body = { id }

        if (env.DB) {
          await env.DB.prepare(
            'UPDATE community_library SET downloads = downloads + 1 WHERE id = ?',
          )
            .bind(body.id)
            .run()

          const item = await env.DB.prepare(
            'SELECT share_string FROM community_library WHERE id = ?',
          )
            .bind(body.id)
            .first<{ share_string: string }>()

          if (!item) return jsonResponse({ error: 'Item not found' }, 404)
          return jsonResponse({ ok: true, shareString: item.share_string })
        }

        return jsonResponse({ ok: true, shareString: '' })
      }

      // ── Global Opt-in Leaderboard ────────────────────────────────────────
      if (path === '/api/v1/leaderboard' && request.method === 'GET') {
        if (!env.DB) {
          return jsonResponse({ ok: true, leaderboard: [] })
        }

        const rows = await env.DB.prepare(
          'SELECT user_id, alias, weekly_xp, streak, level, updated_at FROM public_stats ORDER BY weekly_xp DESC LIMIT 50',
        ).all()

        return jsonResponse({ ok: true, leaderboard: rows.results })
      }

      if (path === '/api/v1/stats/sync' && request.method === 'POST') {
        const parsed = parseStatsSync(await request.json().catch(() => null))
        if (!parsed.ok) return jsonResponse({ error: parsed.error }, 400)
        const body = parsed.value

        const nowIso = new Date().toISOString()
        const cleanAlias = body.alias

        if (env.DB) {
          await env.DB.prepare(
            `INSERT INTO public_stats (user_id, alias, weekly_xp, streak, level, updated_at)
             VALUES (?, ?, ?, ?, ?, ?)
             ON CONFLICT(user_id) DO UPDATE SET
               alias = excluded.alias,
               weekly_xp = excluded.weekly_xp,
               streak = excluded.streak,
               level = excluded.level,
               updated_at = excluded.updated_at`,
          )
            .bind(body.userId, cleanAlias, body.weeklyXp, body.streak, body.level, nowIso)
            .run()
        }

        return jsonResponse({ ok: true })
      }

      // ── Crash Telemetry ──────────────────────────────────────────────────
      if (path === '/api/v1/telemetry/crash' && request.method === 'POST') {
        return handleCrashTelemetry(request, env)
      }

      return jsonResponse({ error: 'Not found' }, 404)
    } catch (err: unknown) {
      // Never echo internal error text (DB/driver messages) to callers; log only the class.
      console.error('worker error', err instanceof Error ? err.name : typeof err)
      if (err instanceof SyntaxError) return jsonResponse({ error: 'Invalid JSON body' }, 400)
      return jsonResponse({ error: 'Internal error' }, 500)
    }
  },
}
